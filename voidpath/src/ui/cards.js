const CLOSING = 'Everything you saw and heard was generated by code.';

export class Cards {
  constructor(ui) {
    this.ui = ui;
    injectCSS('vp-cards', CSS);
    this.isBlocking = false;
    this._cur = null;           // { view, kind, resolve, ... }
    this._captions = new Set(); // { node, resolve, timers }
    this.root = el('div', { class: 'vp-layer vp-cards' });
    ui.root.appendChild(this.root);
  }

  get isOpen() { return !!this._cur; }

  // ------------------------------------------------------------------ cards

  chapter({ kicker = '', title = '', traveler = null, ms = 4500, hold = false } = {}) {
    const k = ms / 4500;
    const letters = el('div', { class: 'vp-chap-kick', 'aria-label': kicker }, [...String(kicker)].map((ch, i) => {
      const s = el('span', { text: ch });
      s.style.setProperty('--i', i);
      return s;
    }));
    const accent = traveler ? this.ui._accentOf(traveler) : '#7fe3ff';
    const trav = traveler ? el('div', { class: 'vp-chap-trav' }, [
      this.ui.portraitEl(traveler, { size: 96, accent }),
      el('div', {}, [el('b', { text: this.ui.memberName(traveler) }), el('small', { text: this.ui.memberClass(traveler) || 'Traveler' })]),
    ]) : null;
    const view = el('div', { class: 'vp-sc vp-sc-black vp-chap', role: 'dialog', 'aria-label': `${kicker} ${title}` }, [
      letters, el('h1', { class: 'vp-chap-title', text: title }), rule(), trav,
    ]);
    view.style.setProperty('--acc', accent);
    setTimeout(() => this.ui.sfx('card'), 1150 * k);
    return this._open(view, 'chapter', { k, ms, fadeOut: 700 * k, wait: hold });
  }

  logo({ text = 'VOIDPATH', ms = 4000, hold = false } = {}) {
    const k = ms / 4000;
    const ghost = (cls) => el('span', { class: `vp-logo-ghost ${cls}`, 'aria-hidden': 'true', text });
    const view = el('div', { class: 'vp-sc vp-sc-logo', role: 'img', 'aria-label': text }, [
      el('h1', { class: 'vp-logo' }, [ghost('c'), ghost('m'), el('span', { class: 'vp-logo-main', text })]), rule(),
    ]);
    return this._open(view, 'logo', { k, ms, fadeOut: 800 * k, wait: hold });
  }

  /** Centred caption over the scene ("En route"); never blocks input. */
  caption(text, { ms = 2500 } = {}) {
    const node = el('div', { class: 'vp-cap-card', role: 'status' }, [el('i'), el('span', {}, [richText(text)]), el('i')]);
    this.root.appendChild(node);
    void node.offsetWidth;
    node.classList.add('is-on');
    const fade = Math.min(450, ms * 0.3);
    node.style.transitionDuration = `${fade}ms`;
    return new Promise((resolve) => {
      const cap = { node, resolve, timers: [] };
      const done = () => { clearTimeout(cap.timers[0]); clearTimeout(cap.timers[1]); node.remove(); this._captions.delete(cap); resolve(); };
      cap.done = done;
      cap.timers = [setTimeout(() => node.classList.remove('is-on'), Math.max(0, ms - fade)), setTimeout(done, ms)];
      this._captions.add(cap);
    });
  }

  clear() {
    this._finish(true);
    for (const cap of [...this._captions]) cap.done();
  }

  credits({ lines = [], transparent = false, onSkip = null, speed = 46 } = {}) {
    const roll = el('div', { class: 'vp-cred-roll' }, lines.map((l) => this._creditLine(l)));
    const end = el('div', { class: 'vp-cred-end' }, [el('p', { text: CLOSING })]);
    this._holdBar = el('i');
    this._holdHint = el('div', { class: 'vp-hold' }, [el('span', { class: 'vp-hold-g' }), 'Hold to skip', el('span', { class: 'vp-hold-bar' }, [this._holdBar])]);
    const view = el('div', { class: `vp-sc vp-cred ${transparent ? 'is-clear' : 'vp-sc-black'}`, role: 'dialog', 'aria-label': 'Credits' }, [roll, end, this._holdHint]);
    // holding a finger anywhere skips too (pointer hold tracked here, Confirm in update)
    view.addEventListener('pointerdown', () => { this._pointerHeld = true; });
    for (const t of ['pointerup', 'pointercancel', 'pointerleave']) view.addEventListener(t, () => { this._pointerHeld = false; });
    const p = this._open(view, 'credits', { k: 1, fadeOut: 900, onSkip });
    Object.assign(this._cur, { roll, end, speed, y: 0, phase: 'roll', held: 0, endT: 0 });
    this._pointerHeld = false;
    this._refreshHoldGlyph();
    return p;
  }

  end({ text = 'THE END', ms = 1600 } = {}) {
    const k = ms / 1600;
    const prompt = el('div', { class: 'vp-end-p' }, [el('span', { class: 'vp-end-g' }), 'Continue']);
    const view = el('div', { class: 'vp-sc vp-sc-black vp-sc-end', role: 'dialog', 'aria-label': text }, [
      el('div', { class: 'vp-end-t', text }), rule(), prompt,
    ]);
    onTap(view, () => { if (this._cur && this._cur.view === view && this._cur.ready) this._finish(); });
    const p = this._open(view, 'end', { k, fadeOut: 600 * k, wait: true });
    prompt.firstChild.replaceChildren(glyph('confirm', this.ui.input.lastDevice));
    setTimeout(() => {
      if (!this._cur || this._cur.view !== view) return;
      this._cur.ready = true;
      prompt.classList.add('is-on');
    }, ms);
    return p;
  }

  // ------------------------------------------------------------------ frame

  update(dt, focused) {
    const c = this._cur;
    if (!c) return;
    if (c.kind === 'credits') this._updateCredits(c, dt, focused);
    if (!focused) return;
    const inp = this.ui.input;
    if (c.kind === 'end' && c.ready && inp.pressed('confirm')) { inp.consume('confirm'); this._finish(); return; }
    for (const a of ['confirm', 'cancel', 'menu']) inp.consume(a);      // cards hold input
  }

  _updateCredits(c, dt, focused) {
    const held = this._pointerHeld || (focused && this.ui.input.down('confirm'));
    c.held = held ? c.held + dt : 0;
    this._holdHint.style.opacity = c.held > 0.05 ? '1' : '';
    this._holdBar.style.setProperty('--p', Math.min(1, c.held).toFixed(3));
    if (c.held >= 1) {
      if (c.onSkip) c.onSkip();
      this._finish();
      return;
    }
    if (c.phase === 'roll') {
      c.y += c.speed * dt;
      const h = this.root.clientHeight;
      c.roll.style.transform = `translateY(${(h - c.y).toFixed(1)}px)`;
      if (c.y > h + c.roll.offsetHeight + 20) { c.phase = 'closing'; c.end.classList.add('is-on'); }
    } else if ((c.endT += dt) > 5.2) {
      c.phase = 'done';
      this._finish();
    } else if (c.endT > 4) c.end.classList.remove('is-on');
  }

  // ------------------------------------------------------------------ plumbing

  _creditLine(l) {
    if (l.gap) return el('div', { style: { height: `${24 * l.gap}px`, flex: 'none' } });
    if (l.head) return el('div', { class: 'vp-cred-head', text: l.head });
    if (l.cast) {
      const accent = this.ui._accentOf(l.cast) || '#7fe3ff';
      const row = el('div', { class: 'vp-cred-cast' }, [
        this.ui.portraitEl(l.cast, { size: 72, accent }),
        el('div', {}, [el('b', { text: l.name || this.ui.memberName(l.cast) }), l.role ? el('small', { text: l.role }) : null]),
      ]);
      row.style.setProperty('--acc', accent);
      return row;
    }
    if (l.role || l.name) return el('div', { class: 'vp-cred-role' }, [el('span', { text: l.role || '' }), el('b', { text: l.name || '' })]);
    return el('div', { class: 'vp-cred-text' }, [richText(l.text || '')]);
  }

  _refreshHoldGlyph() {
    const dev = this.ui.input.lastDevice;
    this._holdHint.firstChild.replaceChildren(dev === 'touch' ? '' : glyph('confirm', dev));
  }

  /** Show a blocking card; it ends after `ms` (or when `wait` cards are confirmed). */
  _open(view, kind, { k = 1, ms = 0, fadeOut = 600, wait = false, onSkip = null } = {}) {
    if (this._cur) this._finish(true);
    view.style.setProperty('--k', k);
    this.root.appendChild(view);
    this.isBlocking = true;
    this.ui._ctxPush('cards', 'card');
    void view.offsetWidth;
    view.classList.add('is-on');
    return new Promise((resolve) => {
      this._cur = { view, kind, resolve, fadeOut, onSkip, ready: false, timer: 0 };
      if (ms && !wait) this._cur.timer = setTimeout(() => this._finish(), Math.max(0, ms - fadeOut));
    });
  }

  _finish(instant = false) {
    const c = this._cur;
    if (!c) return;
    this._cur = null;
    clearTimeout(c.timer);
    this.isBlocking = false;
    this.ui._ctxPop('cards');
    c.view.classList.add('is-out');
    const done = () => { c.view.remove(); c.resolve(); };
    if (instant) done();
    else setTimeout(done, c.fadeOut);
  }
}

/** The amber rule with a diamond (title-screen style). */
function rule() {
  return el('div', { class: 'vp-rule' }, [el('i'), el('b'), el('i')]);
}
