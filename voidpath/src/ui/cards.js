// Full-screen story cards over the scene.
//
//   ui.cards.chapter({ kicker, title, traveler, ms = 4500 }) -> Promise
//       black card: kicker letters fade in, the title with the amber rule, the traveler's portrait
//       and name; input is held until it ends
//   ui.cards.logo({ text = 'VOIDPATH', ms = 4000 }) -> Promise      the logotype over the scene
//   ui.cards.caption(text, { ms = 2500 }) -> Promise                 centred caption, never blocks input
//   ui.cards.credits({ lines, transparent, onSkip, speed }) -> Promise
//       lines: { head } | { role, name } | { cast: charId, name, role } | { text } | { gap: n };
//       scrolls at a readable pace (speed px/s, default 46), then "Everything you saw and heard was
//       generated by code"; holding Confirm (or a finger) for 1 s skips (onSkip is called).
//       transparent: true scrolls over the live field with a dark band behind the text.
//   ui.cards.end({ text = 'THE END' }) -> Promise                    waits for Confirm or a tap
//   ui.cards.clear()     drop every card and caption at once (aborted scripts); their promises resolve
//
// `ms` scales a card's whole timeline (the cutscene runner passes about 300 in skip mode); `hold:
// true` keeps a chapter card or logo up until clear() (previews, screenshots).
// isBlocking is true while a chapter card, logo, credits or THE END is up.

